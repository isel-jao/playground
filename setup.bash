#!/bin/bash

# Regenerate the playground "new-<name>" aliases in ~/.zshrc.
#
# All playground templates live in the templates/ folder next to this script.
# Every direct subdirectory of templates/ becomes an alias:
#   new-<folder>="cp -r $TEMPLATES/<folder> "
# so you can scaffold a copy with e.g.  new-cpp my-experiment
#
# Each generated line ends with a tag comment ($tag). Cleanup is a single
# `grep -vF` on that tag, so the list is discovered at runtime — adding a new
# template folder (cpp, js, rust, ...) needs NO edits here, just re-run this.

setup_playground_aliases() {
    # Templates dir: the argument if given, else templates/ next to this script.
    local script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    local templates_dir="${1:-$script_dir/templates}"
    local zshrc="$HOME/.zshrc"
    local tag="# playground:auto"          # marks every auto-generated line

    # Discover current template folders. Because they all live in templates/,
    # every subdirectory is a template — no files or hidden dirs to filter out.
    local names=() dir
    for dir in "$templates_dir"/*/; do
        [ -d "$dir" ] || continue          # no match -> literal glob, skip it
        names+=("$(basename "$dir")")
    done

    local temp_zshrc
    temp_zshrc="$(mktemp)"

    # Drop every previously generated line by its tag -> idempotent re-runs.
    if [ -f "$zshrc" ]; then
        grep -vF "$tag" "$zshrc" > "$temp_zshrc"
    fi

    # Trim trailing blank lines so the block does not drift down on each run
    # (the blank separator below is untagged, so grep can't remove it for us).
    local kept
    kept="$(< "$temp_zshrc")"
    printf '%s\n' "$kept" > "$temp_zshrc"

    # Append a fresh, fully tagged block built from the folders that exist now.
    {
        echo ""
        echo "# playground aliases (auto-generated by setup.bash) $tag"
        echo "export TEMPLATES=\"$templates_dir\" $tag"
        local name
        for name in "${names[@]}"; do
            echo "alias new-$name=\"cp -r \$TEMPLATES/$name \" $tag"
        done
    } >> "$temp_zshrc"

    mv "$temp_zshrc" "$zshrc"

    echo "Templates directory: $templates_dir"
    echo "Updated aliases in:  $zshrc"
    if [ "${#names[@]}" -gt 0 ]; then
        echo "Aliases: ${names[*]/#/new-}"
    else
        echo "No template folders found."
    fi
    echo "Run 'source ~/.zshrc' (or open a new shell) to load them."
}

# Run it. Optionally pass a custom templates directory as the first argument.
setup_playground_aliases "$@"
